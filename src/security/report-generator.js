/**
 * Pentest Report Generator
 * Generates professional Markdown reports from security findings.
 * Includes CVSS 4.0 scoring, executive summary, and remediation.
 */
import { autoScore } from './cvss4.js';
import { writeFileSync } from 'fs';

/**
 * Generate a Markdown pentest report from findings.
 * @param {object} opts - { target, findings, analyst, date, scope }
 * @returns {{ markdown: string, path: string }}
 */
export function generateReport(opts = {}) {
  const {
    target = 'Unknown Target',
    findings = [],
    analyst = 'Red CLI',
    date = new Date().toISOString().split('T')[0],
    scope = target,
    outputPath
  } = opts;

  // Score all findings
  const scored = findings.map(f => {
    const cvss = autoScore(f);
    return { ...f, cvss };
  });

  // Sort by severity
  const severityOrder = { critical: 0, high: 1, medium: 2, low: 3, info: 4 };
  scored.sort((a, b) => (severityOrder[a.cvss.severity] || 5) - (severityOrder[b.cvss.severity] || 5));

  const critical = scored.filter(f => f.cvss.severity === 'critical');
  const high = scored.filter(f => f.cvss.severity === 'high');
  const medium = scored.filter(f => f.cvss.severity === 'medium');
  const low = scored.filter(f => f.cvss.severity === 'low');
  const info = scored.filter(f => f.cvss.severity === 'info');

  let md = '';

  // Header
  md += `# Penetration Test Report\n\n`;
  md += `| Field | Value |\n|-------|-------|\n`;
  md += `| **Target** | ${target} |\n`;
  md += `| **Scope** | ${scope} |\n`;
  md += `| **Date** | ${date} |\n`;
  md += `| **Analyst** | ${analyst} |\n`;
  md += `| **Tool** | Red CLI v0.4.2 |\n\n`;

  // Executive Summary
  md += `## Executive Summary\n\n`;
  md += `A security assessment was conducted against **${target}**. `;
  md += `The assessment identified **${findings.length}** finding(s):\n\n`;
  md += `| Severity | Count |\n|----------|-------|\n`;
  md += `| 🔴 Critical | ${critical.length} |\n`;
  md += `| 🟠 High | ${high.length} |\n`;
  md += `| 🟡 Medium | ${medium.length} |\n`;
  md += `| 🔵 Low | ${low.length} |\n`;
  md += `| ⚪ Info | ${info.length} |\n\n`;

  if (critical.length > 0) {
    md += `**⚠️ Critical findings require immediate attention.**\n\n`;
  }

  // Findings Detail
  md += `## Findings\n\n`;

  for (let i = 0; i < scored.length; i++) {
    const f = scored[i];
    const icon = { critical: '🔴', high: '🟠', medium: '🟡', low: '🔵', info: '⚪' }[f.cvss.severity] || '⚪';

    md += `### ${i + 1}. ${icon} ${f.title || 'Untitled Finding'}\n\n`;
    md += `| Metric | Value |\n|--------|-------|\n`;
    md += `| **Severity** | ${f.cvss.severity.toUpperCase()} |\n`;
    md += `| **CVSS 4.0** | ${f.cvss.score} |\n`;
    md += `| **Vector** | \`${f.cvss.vector}\` |\n`;
    md += `| **Type** | ${f.cvss.vulnType} |\n`;
    if (f.url) md += `| **URL** | ${f.url} |\n`;
    if (f.param) md += `| **Parameter** | ${f.param} |\n`;
    md += `\n`;

    if (f.detail) md += `**Description:** ${f.detail}\n\n`;
    if (f.evidence) md += `**Evidence:**\n\`\`\`\n${f.evidence.slice(0, 500)}\n\`\`\`\n\n`;
    if (f.remediation) md += `**Remediation:** ${f.remediation}\n\n`;

    md += `---\n\n`;
  }

  // Remediation Summary
  md += `## Remediation Priority\n\n`;
  md += `| # | Finding | Severity | Action |\n|---|---------|----------|--------|\n`;
  for (let i = 0; i < Math.min(scored.length, 10); i++) {
    const f = scored[i];
    const action = f.remediation || getDefaultRemediation(f.cvss.vulnType);
    md += `| ${i + 1} | ${f.title || 'N/A'} | ${f.cvss.severity} | ${action.slice(0, 60)} |\n`;
  }
  md += `\n`;

  // Footer
  md += `## Methodology\n\n`;
  md += `This assessment was performed using Red CLI's automated security tools including:\n`;
  md += `- Passive response analysis (headers, cookies, secrets, PII)\n`;
  md += `- Active vulnerability probes (SQLi, XSS, SSTI, SSRF, LFI, CMDi, CORS, CSRF)\n`;
  md += `- Attack surface mapping and crawling\n`;
  md += `- CVSS 4.0 scoring\n`;
  md += `- Finding correlation and attack chain analysis\n\n`;
  md += `---\n*Generated by Red CLI v0.4.2 on ${date}*\n`;

  // Save to file
  const path = outputPath || `report-${target.replace(/[^a-z0-9]/gi, '-')}-${date}.md`;
  writeFileSync(path, md, 'utf-8');

  return { markdown: md, path, findingCount: findings.length };
}

function getDefaultRemediation(vulnType) {
  const remediations = {
    sqli: 'Use parameterized queries / prepared statements',
    xss: 'Encode output, implement CSP',
    cmdi: 'Avoid shell commands, use safe APIs',
    ssrf: 'Validate/whitelist URLs, block internal ranges',
    lfi: 'Validate file paths, use allowlists',
    ssti: 'Sandbox template engines, escape user input',
    csrf: 'Implement anti-CSRF tokens',
    cors_misconfig: 'Restrict Access-Control-Allow-Origin',
    jwt_none: 'Reject alg:none, validate algorithm server-side',
    jwt_weak_secret: 'Use strong random secret (256+ bits)',
    secret_exposed: 'Remove secrets from responses, rotate keys',
    missing_header: 'Add security headers (HSTS, CSP, X-Frame-Options)',
    open_redirect: 'Validate redirect URLs against allowlist',
    idor: 'Implement proper authorization checks',
    nosqli: 'Sanitize input, use parameterized queries',
  };
  return remediations[vulnType] || 'Review and remediate';
}

export default { generateReport };
